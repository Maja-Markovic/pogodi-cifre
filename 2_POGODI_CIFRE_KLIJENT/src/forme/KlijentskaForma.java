    private void jTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableMouseClicked
        //desni klik na tabelu/ events/ mouse/ mouseClicked
        //kad kliknemo na polje u tabeli okida se ova metoda koja ce pokupiti red i kolonu i poslati zahtev serveru 
        //kada citamo koordinate tabele radimo sa JTable, ne moze sa TableModel
        if (brojPokusaja < 5) {
            JTable tabela = (JTable) evt.getSource();
            Point point = evt.getPoint();
            int red = tabela.rowAtPoint(point);
            int kolona = tabela.columnAtPoint(point);

            if (red != -1 && kolona != -1) {
                System.out.println("KOORDINATE: " + red + " " + kolona);

                KlijentskiZahtev kz = new KlijentskiZahtev();
                kz.setOperacija(Operacije.POGODI_BROJ);
                SkriveniBroj sb = new SkriveniBroj(red, kolona, -1);
                kz.setParam(sb);

                Komunikacija.getInstance().posaljiZahtev(kz);

                ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();

                sb = (SkriveniBroj) so.getOdgovor();

                if (sb == null) {
                    tabela.setValueAt(-1, red, kolona);
                } else {
                    brojPogodjenih++;
                    if (brojPogodjenih == 1) {
                        cifra1 = sb.getVrednost();
                    } else if (brojPogodjenih == 2) {
                        cifra2 = sb.getVrednost();
                    } else {
                        cifra3 = sb.getVrednost();
                    }

                    tabela.setValueAt(sb.getVrednost(), red, kolona);

                    if (brojPogodjenih == 3) {

                        int najveca = Math.max(cifra1, Math.max(cifra2, cifra3));
                        int najmanja = Math.min(cifra1, Math.min(cifra2, cifra3));
                        int srednja = (cifra1 + cifra2 + cifra3) - najveca - najmanja;
                        int broj = najveca * 100 + srednja * 10 + najmanja;
                        JOptionPane.showMessageDialog(null, "POBEDILI STE-sifra: " + broj);
                    }
                }
                brojPokusaja++;
            }
            if (brojPokusaja >= 5) {
                JOptionPane.showMessageDialog(null, "IZGUBILI STE");
                KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.NOVA_IGRA, null);
                Komunikacija.getInstance().posaljiZahtev(kz);
                try {
                    Komunikacija.getInstance().getS().close();
                } catch (IOException ex) {
                    Logger.getLogger(KlijentskaForma.class.getName()).log(Level.SEVERE, null, ex);
                }

                this.dispose();
            }

        }
    }//GEN-LAST:event_jTableMouseClicked

