    public void pokreniIgru() {
        jButtonPokreniIgru.setEnabled(false);
        jLabelUlogovani.setText("Zdravo, " + ulogovani.getIme() + " " + ulogovani.getPrezime());

        resetujTabelu();

        jTable.getModel().addTableModelListener(new TableModelListener() {
            @Override
            public void tableChanged(TableModelEvent e) {

                if (Controller.getInstance().getBrojevi().size() >= 3) {
                    JOptionPane.showMessageDialog(null, "VEC SU UNETA 3 BROJA");
                } else {
                    int red = e.getFirstRow();
                    int kolona = e.getColumn();
                    TableModel model = (TableModel) e.getSource();
                    if (model.getValueAt(red, kolona) != null) {
                        //kada broj vec postoji i metoda pozove samu sebe, nece baciti gresku
                        int vrednost = (int) model.getValueAt(red, kolona);
                        SkriveniBroj sb = new SkriveniBroj(red, kolona, vrednost);

                        boolean postoji = Controller.getInstance().postoji(sb);

                        if (postoji) {
                            //brisemo broj iz polja ako taj broj postoji
                            model.setValueAt(null, red, kolona);
                            JOptionPane.showMessageDialog(null, "TAJ BROJ VEC POSTOJI");
                        } else {
                            Controller.getInstance().dodajBroj(sb);
                            if (Controller.getInstance().getBrojevi().size() == 3) {
                                jButtonPokreniIgru.setEnabled(true);
                            }
                        }
                    }
                }
            }
        });
    }

